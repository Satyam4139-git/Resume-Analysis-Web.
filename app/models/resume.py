from app.models.career_profile import CareerProfile


class Resume:
    """
    Represents a parsed resume.

    Stores basic resume information together with a
    universal CareerProfile generated by AI.
    """

    def __init__(
        self,
        name="",
        email="",
        phone="",
        skills=None,
        experience="",
        education=None,
        projects=None,
        resume_score=0,
        summary="",
        career_profile=None,
    ):

        self.name = name
        self.email = email
        self.phone = phone

        self.skills = self._normalize_string_list(skills)

        self.experience = self._normalize_experience(experience)

        self.education = self._normalize_string_list(education)

        self.projects = self._normalize_string_list(projects)

        self.resume_score = resume_score

        self.summary = summary if isinstance(summary, str) else str(summary)

        self.career_profile = (
            career_profile
            if career_profile
            else CareerProfile()
        )

        # Filled in by app.utils.seniority.apply_seniority()
        self.experience_years = 0.0
        self.experience_level = 0

    # ==========================================================
    # NORMALIZATION HELPERS
    # ==========================================================

    @staticmethod
    def _normalize_string_list(value):
        """
        Converts AI-generated arrays into clean string lists.

        Handles:

            ["Python", "SQL"]

        and also:

            [{"name": "Python"}, {"name": "SQL"}]

        and:

            [{"skill": "Python"}]

        """

        if value is None:
            return []

        if not isinstance(value, list):
            return [str(value)]

        result = []

        for item in value:

            # Already a string
            if isinstance(item, str):

                cleaned = item.strip()

                if cleaned:
                    result.append(cleaned)

                continue

            # AI returned a dictionary
            if isinstance(item, dict):

                # Try common AI field names
                possible_keys = [
                    "name",
                    "skill",
                    "title",
                    "value",
                    "text",
                    "description",
                ]

                extracted = None

                for key in possible_keys:

                    if key in item and item[key] is not None:

                        extracted = item[key]

                        break

                if extracted is not None:

                    if isinstance(extracted, str):

                        cleaned = extracted.strip()

                        if cleaned:
                            result.append(cleaned)

                    else:

                        result.append(
                            str(extracted)
                        )

                else:

                    # Last-resort conversion
                    result.append(
                        str(item)
                    )

                continue

            # Any other unexpected value
            result.append(
                str(item)
            )

        return result

    @staticmethod
    def _normalize_experience(value):
        """
        Normalizes experience into a string.

        AI may sometimes return a list or dictionary
        even though the schema expects a string.
        """

        if value is None:
            return ""

        if isinstance(value, str):
            return value.strip()

        if isinstance(value, list):

            parts = []

            for item in value:

                if isinstance(item, str):

                    parts.append(item.strip())

                elif isinstance(item, dict):

                    # Convert useful dictionary fields
                    title = item.get(
                        "title",
                        item.get(
                            "role",
                            item.get(
                                "position",
                                ""
                            )
                        )
                    )

                    company = item.get(
                        "company",
                        item.get(
                            "organization",
                            ""
                        )
                    )

                    description = item.get(
                        "description",
                        item.get(
                            "details",
                            ""
                        )
                    )

                    text_parts = []

                    if title:
                        text_parts.append(str(title))

                    if company:
                        text_parts.append(str(company))

                    if description:
                        text_parts.append(str(description))

                    if text_parts:

                        parts.append(
                            " - ".join(text_parts)
                        )

                    else:

                        parts.append(
                            str(item)
                        )

                else:

                    parts.append(
                        str(item)
                    )

            return " ".join(
                part for part in parts if part
            )

        if isinstance(value, dict):

            title = value.get(
                "title",
                value.get(
                    "role",
                    value.get(
                        "position",
                        ""
                    )
                )
            )

            company = value.get(
                "company",
                value.get(
                    "organization",
                    ""
                )
            )

            description = value.get(
                "description",
                value.get(
                    "details",
                    ""
                )
            )

            parts = []

            if title:
                parts.append(str(title))

            if company:
                parts.append(str(company))

            if description:
                parts.append(str(description))

            if parts:
                return " - ".join(parts)

            return str(value)

        return str(value)

    # ==========================================================
    # FROM DICT
    # ==========================================================

    @classmethod
    def from_dict(cls, data):
        """
        Creates a Resume object from a dictionary.

        AI responses are normalized here so that the
        rest of the application always receives the
        expected data types.
        """

        if not isinstance(data, dict):

            raise ValueError(
                "Resume data must be a dictionary."
            )

        career_profile_data = data.get(
            "career_profile",
            {}
        )

        if not isinstance(
            career_profile_data,
            dict
        ):

            career_profile_data = {}

        return cls(

            name=data.get(
                "name",
                ""
            ),

            email=data.get(
                "email",
                ""
            ),

            phone=data.get(
                "phone",
                ""
            ),

            skills=data.get(
                "skills",
                []
            ),

            experience=data.get(
                "experience",
                ""
            ),

            education=data.get(
                "education",
                []
            ),

            projects=data.get(
                "projects",
                []
            ),

            resume_score=data.get(
                "resume_score",
                0
            ),

            summary=data.get(
                "summary",
                ""
            ),

            career_profile=CareerProfile.from_dict(
                career_profile_data
            ),
        )

    # ==========================================================
    # TO DICT
    # ==========================================================

    def to_dict(self):
        """
        Converts Resume object to dictionary.
        """

        return {

            "name": self.name,

            "email": self.email,

            "phone": self.phone,

            "skills": self.skills,

            "experience": self.experience,

            "education": self.education,

            "projects": self.projects,

            "resume_score": self.resume_score,

            "summary": self.summary,

            "experience_years": self.experience_years,

            "experience_level": self.experience_level,

            "career_profile": (
                self.career_profile.to_dict()
                if self.career_profile
                else {}
            ),
        }